#!/usr/bin/env python3
"""
catalog_results.py
==================
Audit every analysis script and every result file, and classify each by whether
it is still scientifically valid.

Three defects have been found in this project, each of which invalidates a
subset of earlier results. They are detectable from script source:

  CATALOG_OLD    the script reads data/results/ssw_event_catalog.csv, the
                 manuscript's 16-event list. That list contains 2012-01-11
                 (not a major SSW in any of six reanalyses) and omits
                 2000-03-20 and 2010-03-24. Superseded by ssw_canonical.csv.
  DETECTOR       the script calls a locally implemented Charlton-Polvani
                 detector, which over-detects (40 events 1979-2024 vs 31
                 canonical), admitting final warmings and double counts.
  SINGLE_WINDOW  the script fits ONE lag-window indicator at a time, so the
                 control group for any window includes the post-onset response.
                 R113 demonstrated on the AO that this specification is not
                 sound. Superseded by the event-study form (r113/r114).

Scripts are matched to their outputs by scanning for result paths written.

Outputs: RESULTS_CATALOG.md
         data/results/results_catalog.json
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "scripts"
RESULTS = ROOT / "data" / "results"
OUT_MD = ROOT / "docs" / "RESULTS_CATALOG.md"
OUT_JSON = RESULTS / "results_catalog.json"

SKIP = {"__pycache__"}

# scripts implementing the corrected design (hand-curated; these define current truth)
CURRENT = {
    "r113_event_study.py", "r114_avalanche_event_study.py",
    "condpois.py", "download_ssw_compendium_canonical.py",
    "download_lawis_full.py", "download_albina_caaml_problems.py",
    "inventory_datasets.py", "catalog_results.py",
    "ng_fig_design_artifact.py",
}
# scripts known to use the single-window specification superseded by r113/r114
SINGLE_WINDOW = {
    "r106_canonical_catalog_headline.py", "r107_pooled_within_winter.py",
    "r108_pwl_seasonal_control.py", "r109_norway_problem_mechanism.py",
    "r110_albina_alpine_problems.py", "r111_kinetic_growth_instrumental.py",
    "r112_design_positive_control.py", "r104_accident_case_crossover.py",
    "r105_multiregion_meta.py",
}


def scan(p):
    try:
        src = p.read_text(encoding="utf8", errors="replace")
    except Exception:
        return None
    flags = []
    if "ssw_event_catalog" in src:
        flags.append("CATALOG_OLD")
    if re.search(r"def detect_ssw|detect_ssw\(", src):
        flags.append("DETECTOR")
    if p.name in SINGLE_WINDOW:
        flags.append("SINGLE_WINDOW")
    if "ssw_canonical" in src:
        flags.append("uses_canonical_catalog")
    outs = sorted(set(re.findall(r"data/results/([A-Za-z0-9_\-.]+\.(?:json|csv|parquet|txt))", src)))
    doc = ""
    m = re.search(r'"""(.*?)"""', src, re.S)
    if m:
        lines = [l.strip() for l in m.group(1).strip().splitlines() if l.strip()]
        for l in lines[1:]:
            if not set(l) <= set("=-_ "):
                doc = l
                break
    return {"flags": flags, "outputs": outs, "doc": doc[:160],
            "lines": src.count("\n") + 1}


def status_of(name, flags):
    if name in CURRENT:
        return "CURRENT"
    bad = [f for f in flags if f in ("CATALOG_OLD", "DETECTOR", "SINGLE_WINDOW")]
    if bad:
        return "SUPERSEDED"
    return "UNREVIEWED"


def main():
    scripts, produced = {}, {}
    for p in sorted(SCRIPTS.rglob("*.py")):
        if any(s in p.parts for s in SKIP):
            continue
        info = scan(p)
        if info is None:
            continue
        rel = str(p.relative_to(ROOT)).replace("\\", "/")
        info["status"] = status_of(p.name, info["flags"])
        scripts[rel] = info
        for o in info["outputs"]:
            produced.setdefault(o, []).append(rel)

    files = sorted(f.name for f in RESULTS.iterdir() if f.is_file())
    orphan_results = [f for f in files if f not in produced and f != "results_catalog.json"]

    counts = {}
    for v in scripts.values():
        counts[v["status"]] = counts.get(v["status"], 0) + 1

    # result status inherits from its producing script(s)
    res_status = {}
    for f in files:
        srcs = produced.get(f, [])
        sts = {scripts[s]["status"] for s in srcs if s in scripts}
        res_status[f] = ("CURRENT" if "CURRENT" in sts else
                         "SUPERSEDED" if "SUPERSEDED" in sts else
                         "UNREVIEWED" if sts else "ORPHAN")

    L = ["# Results catalogue", "",
         "Generated by `scripts/utilities/catalog_results.py` (re-runnable).", "",
         f"**{len(scripts)} scripts**, **{len(files)} result files**.", "",
         "## Validity classification", "",
         "Three defects invalidate subsets of earlier work. Each is detected from script source:",
         "",
         "| flag | meaning |",
         "|---|---|",
         "| `CATALOG_OLD` | uses the manuscript's 16-event list, which contains a non-event (2012-01-11) and omits two real SSWs |",
         "| `DETECTOR` | uses the local Charlton–Polvani detector, which over-detects (40 vs 31 canonical) |",
         "| `SINGLE_WINDOW` | fits one lag window at a time; control group contains the post-onset response (superseded by r113/r114) |",
         "", "## Script status", "",
         "| status | n |", "|---|---|"]
    for k in ("CURRENT", "SUPERSEDED", "UNREVIEWED"):
        L.append(f"| {k} | {counts.get(k, 0)} |")
    L += ["", "### CURRENT — the corrected pipeline", "",
          "| script | produces | purpose |", "|---|---|---|"]
    for rel, v in sorted(scripts.items()):
        if v["status"] == "CURRENT":
            L.append(f"| `{rel}` | {', '.join(v['outputs']) or '—'} | {v['doc']} |")

    L += ["", "### SUPERSEDED — do not cite without recomputation", "",
          "| script | defects | produces |", "|---|---|---|"]
    for rel, v in sorted(scripts.items()):
        if v["status"] == "SUPERSEDED":
            bad = ", ".join(f for f in v["flags"] if f in
                            ("CATALOG_OLD", "DETECTOR", "SINGLE_WINDOW"))
            L.append(f"| `{rel}` | {bad} | {', '.join(v['outputs']) or '—'} |")

    L += ["", f"### UNREVIEWED — {counts.get('UNREVIEWED', 0)} scripts", "",
          "Predate the verification rounds; not individually audited. Most are",
          "exploratory or produce figures. Treat any numeric claim from these as",
          "unverified until recomputed under the current design.", ""]

    L += ["## Result files with no producing script "
          f"({len(orphan_results)})", "",
          "These exist in `data/results/` but no script writes them by that name —",
          "either renamed, hand-made, or produced by a since-deleted script.", ""]
    for f in orphan_results[:40]:
        L.append(f"- `{f}`")
    if len(orphan_results) > 40:
        L.append(f"- … and {len(orphan_results) - 40} more")

    OUT_MD.write_text("\n".join(L), encoding="utf8")
    OUT_JSON.write_text(json.dumps(
        {"scripts": scripts, "result_status": res_status,
         "orphan_results": orphan_results}, indent=1), encoding="utf8")

    print(f"scripts: {len(scripts)}  results: {len(files)}")
    for k in ("CURRENT", "SUPERSEDED", "UNREVIEWED"):
        print(f"  {k:12s} {counts.get(k, 0)}")
    print(f"  orphan result files: {len(orphan_results)}")
    print(f"wrote {OUT_MD} and {OUT_JSON}")


if __name__ == "__main__":
    main()
